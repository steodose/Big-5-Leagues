"""Write the dashboard payload to `site/data.json` and `site/data.js`.

`data.json` is fetched over http by the live site; `data.js` assigns the same
payload to `window.BIG5_DATA` so the page also works when opened from `file://`.
"""
from __future__ import annotations

import datetime
import json
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent / "site"

# Slim each team row to the fields the frontend actually reads.
_FIELDS = [
    "abbrev", "name", "short_name", "logo", "color",
    "position", "rank", "games_played", "wins", "draws", "losses",
    "points", "ppg", "goals_for", "goals_against", "goal_diff",
    "note", "note_color", "zone", "form",
    # simulation outputs
    "proj_points", "proj_gd", "avg_finish",
    "p_title", "p_ucl", "p_europe", "p_releg",
]


def _slim(team: dict) -> dict:
    return {k: team.get(k) for k in _FIELDS}


def write(leagues: list[dict], season: int, sources: list[str],
          sim_n: int | None = None, as_of: str | None = None) -> Path:
    """leagues: [{key, name, country, logo, teams, zones, sim}, ...]."""
    meta = {
        "generated": datetime.datetime.now(datetime.timezone.utc)
        .strftime("%Y-%m-%d %H:%M UTC"),
        "season": season,
        "season_label": f"{season}/{(season + 1) % 100:02d}",
        "sources": sources,
    }
    if sim_n:
        meta["sim"] = {"n_sims": sim_n}
    if as_of:
        meta["as_of"] = as_of
    out = {
        "meta": meta,
        "leagues": [
            {
                "key": lg["key"],
                "name": lg["name"],
                "country": lg["country"],
                "logo": lg["logo"],
                "zones": lg["zones"],
                "sim": lg.get("sim"),
                "teams": [_slim(t) for t in lg["teams"]],
            }
            for lg in leagues
        ],
    }

    SITE.mkdir(parents=True, exist_ok=True)
    text = json.dumps(out, indent=1, ensure_ascii=False)
    json_path = SITE / "data.json"
    json_path.write_text(text + "\n", encoding="utf-8")
    (SITE / "data.js").write_text(
        "// Auto-generated by run.py — do not edit.\n"
        "window.BIG5_DATA = " + text + ";\n",
        encoding="utf-8",
    )
    return json_path
